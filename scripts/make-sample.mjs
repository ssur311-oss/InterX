// 엑셀 날짜는 1899-12-30부터 지난 일수. 시간대 영향을 받지 않게 직접 계산한다
function excelSerial(text) {
  const [d, t] = text.split(' ')
  const [y, m, day] = d.split('-').map(Number)
  const [h, mi] = t.split(':').map(Number)
  return (Date.UTC(y, m - 1, day, h, mi) - Date.UTC(1899, 11, 30)) / 86_400_000
}

const sheet = XLSX.utils.aoa_to_sheet([HEADERS, ...ROWS])
ROWS.forEach((row, i) => {
  const ref = XLSX.utils.encode_cell({ r: i + 1, c: 4 })
  sheet[ref] = { t: 'n', v: excelSerial(row[4]), z: 'yyyy-mm-dd hh:mm' }
  sheet[XLSX.utils.encode_cell({ r: i + 1, c: 5 })].z = '#,##0'
})
sheet['!cols'] = [28, 14, 8, 10, 18, 12, 12, 26, 8].map((wch) => ({ wch }))

const book = XLSX.utils.book_new()
XLSX.utils.book_append_sheet(book, sheet, '집행내역')
fs.mkdirSync('sample', { recursive: true })
fs.writeFileSync('sample/sample_expenses.xlsx', XLSX.write(book, { type: 'buffer', bookType: 'xlsx' }))
